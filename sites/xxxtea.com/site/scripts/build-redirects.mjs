// Generate site/public/_redirects from the affiliate registry.
// Single source of truth: site/src/lib/affiliate.ts
//   - sku.asin populated → /go/<id> redirects to /dp/<asin>?tag=...  (direct)
//   - sku.asin empty     → /go/<id> redirects to /s?k=...&tag=...    (search fallback)
//
// Run from project root: node site/scripts/build-redirects.mjs

import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const TS_PATH = path.join(ROOT, 'src/lib/affiliate.ts');
const OUT = path.join(ROOT, 'public/_redirects');

const TAG = process.env.PUBLIC_AMAZON_TAG || 'xxxtea-20';

async function readRegistry() {
  const src = await fs.readFile(TS_PATH, 'utf8');
  const skuBlocks = src
    .split(/\{\s*\n\s*id:/)
    .slice(1)
    .map((block) => '{\n  id:' + block.split(/\n\s*\},?/)[0] + '\n  }');

  const skus = [];
  for (const block of skuBlocks) {
    const id    = block.match(/id:\s*'([^']+)'/)?.[1];
    const asin  = block.match(/asin:\s*'([^']+)'/)?.[1] || '';
    const query = block.match(/searchQuery:\s*'([^']+)'/)?.[1];
    const form  = block.match(/form:\s*'([^']+)'/)?.[1];
    if (id && query) skus.push({ id, asin, searchQuery: query, form });
  }
  return skus;
}

function targetFor(sku) {
  if (/^B[A-Z0-9]{9}$/.test(sku.asin)) {
    return `https://www.amazon.com/dp/${sku.asin}?tag=${TAG}&ascsubtag=${encodeURIComponent(sku.id)}`;
  }
  const q = encodeURIComponent(sku.searchQuery).replace(/%20/g, '+');
  return `https://www.amazon.com/s?k=${q}&tag=${TAG}&ascsubtag=${encodeURIComponent(sku.id)}`;
}

const HEADER = `# AUTO-GENERATED by site/scripts/build-redirects.mjs — DO NOT EDIT BY HAND.
# Affiliate cloaking. /go/<id> → tagged Amazon URL.
# Disallowed in robots.txt to prevent crawl waste.
# Source of truth: src/lib/affiliate.ts (asin → /dp/, otherwise → /s?k=).
`;

const FOOTER = `
# Safety
/admin/*  /404  302
/api/*    /404  302
`;

function pad(s, n) { return s + ' '.repeat(Math.max(1, n - s.length)); }

async function main() {
  const skus = await readRegistry();
  const groups = {};
  for (const sku of skus) (groups[sku.form] ||= []).push(sku);

  const formOrder = ['loose', 'pyramid', 'paper', 'powder', 'kettle', 'teapot', 'infuser', 'set', 'accessory'];
  const lines = [HEADER];

  let direct = 0, search = 0;
  for (const form of formOrder) {
    const items = groups[form];
    if (!items) continue;
    lines.push(`# ${form[0].toUpperCase() + form.slice(1)}`);
    for (const sku of items) {
      const target = targetFor(sku);
      const isDirect = target.includes('/dp/');
      isDirect ? direct++ : search++;
      lines.push(`/go/${pad(sku.id, 36)} ${target}  302`);
    }
  }

  lines.push(FOOTER);

  await fs.writeFile(OUT, lines.join('\n'));
  console.log(`✓ wrote ${OUT}`);
  console.log(`  ${skus.length} SKUs · ${direct} direct (/dp/) · ${search} search (/s?k=)`);
}

main().catch((e) => { console.error(e); process.exit(1); });
